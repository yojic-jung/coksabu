package lesson.member.model;

public class LessonCertify {
	
	private String email;
	private String name;
	private String account;
	private String accountNumber;
	private String serviceAgree;
	private String myAgree;
	
	public void setEmail(String email) {
		this.email = email;
	}
	public String getEmail() {
		return email;
	}
	public void setName(String name) {
		this.name = name;
	}
	public String getName() {
		return name;
	}

	public void setAccount(String account) {
		this.account = account;
	}
	public String getAccount() {
		return account;
	}
	
	public void setAccountNumber(String accountNumber) {
		this.accountNumber = accountNumber;
	}
	public String getAccountNumber() {
		return accountNumber;
	}
	
	public void setServiceAgree(String serviceAgree) {
		this.serviceAgree = serviceAgree;
	}
	public String getServiceAgree() {
		return serviceAgree;
	}
	
	public void setMyAgree(String myAgree) {
		this.myAgree = myAgree;
	}
	public String getMyAgree() {
		return myAgree;
	}
	
}
